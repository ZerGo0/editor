package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
)

const (
	svgDir       = "svg"
	tableFile    = "table_gen.go"
	licenseFile  = "LICENSE-material-icon-theme.md"
	filePerm     = 0o644
	dirPerm      = 0o755
	licenseIntro = `# Material Icon Theme

The SVG icons in the svg directory come from Material Icon Theme,
https://github.com/material-extensions/vscode-material-icon-theme,
at commit ` + themeCommit + `.
The icons are minified. The open folder icons and the default icons are
derived with the paths that the theme's own build scripts use.

`
)

func writeOutputs(dir string, t *table, license []byte) error {
	if err := writeSVGs(filepath.Join(dir, svgDir), t.files); err != nil {
		return err
	}
	src, err := renderTable(t)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, tableFile), src, filePerm); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, licenseFile), append([]byte(licenseIntro), license...), filePerm)
}

func writeSVGs(dir string, files map[string][]byte) error {
	old, err := filepath.Glob(filepath.Join(dir, "*"+svgSuffix))
	if err != nil {
		return err
	}
	for _, p := range old {
		if err := os.Remove(p); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(dir, dirPerm); err != nil {
		return err
	}
	for _, name := range slices.Sorted(maps.Keys(files)) {
		if err := os.WriteFile(filepath.Join(dir, name), files[name], filePerm); err != nil {
			return err
		}
	}
	return nil
}

func renderTable(t *table) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/fileicons/gen. DO NOT EDIT.\n\npackage fileicons\n\n")
	fmt.Fprintf(&b, "const themeCommit = %q\n\n", themeCommit)
	fmt.Fprintf(&b, "const (\n\tdefaultFileIcon   = %q\n\tdefaultFolderIcon = %q\n\trootFolderIcon    = %q\n)\n\n",
		defaultFileName, defaultFolderName, rootFolderName)
	b.WriteString("var iconDefs = []iconDef{\n")
	for _, d := range t.defs {
		fmt.Fprintf(&b, "\t{name: %q, dark: %q", d.name, d.dark)
		if d.light != "" {
			fmt.Fprintf(&b, ", light: %q", d.light)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	writeMap(&b, "fileNameIcons", t.fileNames)
	writeMap(&b, "extensionIcons", t.extensions)
	writeMap(&b, "folderNameIcons", t.folders)
	writeMap(&b, "languageIcons", t.languages)
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format table: %w", err)
	}
	return out, nil
}

func writeMap(b *bytes.Buffer, name string, m map[string]string) {
	fmt.Fprintf(b, "var %s = map[string]string{\n", name)
	for _, k := range slices.Sorted(maps.Keys(m)) {
		fmt.Fprintf(b, "\t%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n\n")
}
