package main

import (
	"archive/tar"
	"bufio"
	"bytes"
	"compress/gzip"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode"
)

const (
	packageVersion = "4.4.0"
	tarballURL     = "https://registry.npmjs.org/@hugeicons/core-free-icons/-/core-free-icons-" + packageVersion + ".tgz"
	iconDir        = "package/dist/esm/"
	listFile       = "icons.txt"
	licenseFile    = "LICENSE-hugeicons.md"
	goFile         = "icons_gen.go"
	filePerm       = 0o644
	filledOption   = "filled"
)

var (
	elementPattern   = regexp.MustCompile(`\["(\w+)",\s*\{([^}]*)\}\]`)
	attributePattern = regexp.MustCompile(`(\w+):\s*"([^"]*)"`)
	namePattern      = regexp.MustCompile(`^[a-z][a-z0-9-]*$`)
)

type icon struct {
	name, source string
	filled       bool
}

func main() {
	icons, err := readList(listFile)
	if err != nil {
		log.Fatal(err)
	}
	files, err := download(icons)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(licenseFile, files[licenseFile], filePerm); err != nil {
		log.Fatal(err)
	}
	old, _ := filepath.Glob("*.svg")
	for _, p := range old {
		if err := os.Remove(p); err != nil {
			log.Fatal(err)
		}
	}
	for _, ic := range icons {
		svg, err := toSVG(files[ic.source], ic.filled)
		if err != nil {
			log.Fatalf("%s: %v", ic.source, err)
		}
		if err := os.WriteFile(ic.name+".svg", []byte(svg), filePerm); err != nil {
			log.Fatal(err)
		}
	}
	if err := writeGo(icons); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d icons\n", len(icons))
}

func readList(path string) ([]icon, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var icons []icon
	s := bufio.NewScanner(f)
	for line := 1; s.Scan(); line++ {
		fields := strings.Fields(s.Text())
		if len(fields) == 0 {
			continue
		}
		if len(fields) < 2 || len(fields) > 3 || !namePattern.MatchString(fields[0]) || len(fields) == 3 && fields[2] != filledOption {
			return nil, fmt.Errorf("%s:%d: want \"<name> <HugeiconsName> [%s]\"", path, line, filledOption)
		}
		icons = append(icons, icon{name: fields[0], source: fields[1], filled: len(fields) == 3})
	}
	return icons, s.Err()
}

func download(icons []icon) (map[string][]byte, error) {
	want := map[string]string{"package/LICENSE.md": licenseFile}
	for _, ic := range icons {
		want[iconDir+ic.source+".js"] = ic.source
	}
	res, err := http.Get(tarballURL)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download %s: %s", tarballURL, res.Status)
	}
	gz, err := gzip.NewReader(res.Body)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	r := tar.NewReader(gz)
	for {
		h, err := r.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		if name, ok := want[h.Name]; ok {
			if files[name], err = io.ReadAll(r); err != nil {
				return nil, err
			}
		}
	}
	for _, name := range want {
		if files[name] == nil {
			return nil, fmt.Errorf("Hugeicons %s has no %s", packageVersion, name)
		}
	}
	return files, nil
}

func toSVG(js []byte, filled bool) (string, error) {
	var b strings.Builder
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none">`)
	elements := elementPattern.FindAllSubmatch(js, -1)
	if len(elements) == 0 {
		return "", fmt.Errorf("no SVG elements")
	}
	for _, el := range elements {
		fmt.Fprintf(&b, "<%s", el[1])
		for _, a := range attributePattern.FindAllSubmatch(el[2], -1) {
			key, value := string(a[1]), string(a[2])
			switch {
			case key == "key":
				continue
			case filled && key == "stroke":
				key = "fill"
			}
			fmt.Fprintf(&b, ` %s="%s"`, kebab(key), value)
		}
		b.WriteString("/>")
	}
	b.WriteString("</svg>\n")
	return b.String(), nil
}

func kebab(s string) string {
	var b strings.Builder
	for _, r := range s {
		if unicode.IsUpper(r) {
			b.WriteByte('-')
			r = unicode.ToLower(r)
		}
		b.WriteRune(r)
	}
	return b.String()
}

func goName(name string) string {
	parts := strings.Split(name, "-")
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func writeGo(icons []icon) error {
	sorted := slices.Clone(icons)
	slices.SortFunc(sorted, func(a, b icon) int { return strings.Compare(a.name, b.name) })
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/icons/gen. DO NOT EDIT.\n\npackage icons\n\nvar (\n")
	for _, ic := range sorted {
		fmt.Fprintf(&b, "\t%s = load(%q)\n", goName(ic.name), ic.name)
	}
	b.WriteString(")\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(goFile, src, filePerm)
}
